<?php
declare(strict_types=1);

require_once __DIR__ . '/config/app.php';
require_once __DIR__ . '/config/database.php';
require_once __DIR__ . '/core/Security.php';
require_once __DIR__ . '/database/seed.php';

$status = null;
$logs   = [];
$error  = null;
$cfg    = Database::config();

$formDb = [
    'host'     => (string)($_POST['db_host'] ?? $cfg['host']),
    'port'     => (string)($_POST['db_port'] ?? $cfg['port']),
    'database' => (string)($_POST['db_name'] ?? $cfg['database']),
    'username' => (string)($_POST['db_user'] ?? $cfg['username']),
    'password' => (string)($_POST['db_pass'] ?? $cfg['password']),
    'timezone' => (string)($_POST['app_tz'] ?? env('APP_TIMEZONE', 'Asia/Makassar')),
];

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    try {
        $dbNameClean = trim($formDb['database']);
        if ($dbNameClean === '') {
            throw new RuntimeException('Nama database wajib diisi.');
        }

        $tzOffsetMap = [
            'Asia/Jakarta'  => '+07:00',
            'Asia/Makassar' => '+08:00',
            'Asia/Jayapura' => '+09:00',
        ];
        $dbTz = $tzOffsetMap[$formDb['timezone']] ?? '+08:00';

        // 1. Try creating DB if permitted; on cPanel/shared hosting where DB is pre-created, fall back directly
        $override = [
            'host'     => trim($formDb['host']),
            'port'     => trim($formDb['port']) ?: '3306',
            'database' => $dbNameClean,
            'username' => trim($formDb['username']),
            'password' => $formDb['password'],
            'timezone' => $dbTz,
        ];

        try {
            $pdoNoDb = Database::pdoWithoutDb($override);
            $safeDbIdent = str_replace('`', '', $dbNameClean);
            $pdoNoDb->exec("CREATE DATABASE IF NOT EXISTS `{$safeDbIdent}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
            $logs[] = "Database `{$safeDbIdent}` diverifikasi / dibuat.";
        } catch (Throwable) {
            $logs[] = "Melewati CREATE DATABASE (mode shared hosting/cPanel) — langsung menghubungkan ke database `{$dbNameClean}`.";
        }

        $pdo = Database::pdo($override);

        // 2. Write .env automatically so server credentials stay outside Git & never break on git pull
        $escEnv = static fn(string $v): string => '"' . str_replace(['\\', '"'], ['\\\\', '\"'], $v) . '"';
        $envContent = implode("\n", [
            '# Auto-generated by EduPresensi Installer',
            'DB_HOST=' . $escEnv($override['host']),
            'DB_PORT=' . $escEnv($override['port']),
            'DB_NAME=' . $escEnv($override['database']),
            'DB_USER=' . $escEnv($override['username']),
            'DB_PASS=' . $escEnv($override['password']),
            'APP_TIMEZONE=' . $escEnv($formDb['timezone']),
            'DB_TIMEZONE=' . $escEnv($dbTz),
            'APP_BASE_PATH=',
            '',
        ]);
        file_put_contents(APP_ROOT . DIRECTORY_SEPARATOR . '.env', $envContent);
        $logs[] = 'File .env berhasil disimpan otomatis (aman saat git pull / update server).';

        // 3. Run schema.sql
        $schemaSql = file_get_contents(__DIR__ . '/database/schema.sql');
        if ($schemaSql === false) {
            throw new RuntimeException('File database/schema.sql tidak ditemukan.');
        }
        $pdo->exec($schemaSql);
        $logs[] = 'Seluruh tabel schema.sql berhasil dibuat / diverifikasi.';

        // 4. Run seed.php
        $seedLogs = run_saas_seed($pdo);
        $logs = array_merge($logs, $seedLogs ?: ['Data demo sudah tersedia.']);

        // 5. Auto-update display_domain if deployed on a live non-localhost domain
        $liveHost = app_host();
        if ($liveHost !== '' && !str_starts_with($liveHost, 'localhost') && !str_starts_with($liveHost, '127.0.0.1')) {
            $displayDomain = $liveHost . app_base_path();
            $pdo->prepare("UPDATE saas_settings SET display_domain = ? WHERE id = 1")->execute([$displayDomain]);
            $logs[] = "Domain tampilan SaaS otomatis disesuaikan ke: {$displayDomain}";
        }

        // 6. Ensure uploads subdirectories exist
        foreach (['branding', 'attendance', 'corrections', 'avatars'] as $sub) {
            $dir = UPLOAD_DIR . DIRECTORY_SEPARATOR . $sub;
            if (!is_dir($dir)) {
                mkdir($dir, 0755, true);
            }
        }
        $logs[] = 'Direktori upload berhasil disiapkan.';
        $status = 'success';
    } catch (Throwable $e) {
        $status = 'error';
        $error = $e->getMessage();
    }
}

